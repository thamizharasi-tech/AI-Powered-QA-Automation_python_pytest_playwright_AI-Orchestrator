_AI_GENERATED_MARKER = "# AUTO-GENERATED BY AI QA ORCHESTRATOR — DO NOT EDIT MANUALLY"


def _derive_script_filename(script_content: str, req_hash: str) -> str:
    code_start = 0
    import_match = re.search(r'^(?:import |from )', script_content, re.MULTILINE)
    if import_match:
        code_start = import_match.start()
    code_section = script_content[code_start:]

    feature_match = re.search(r'@allure\.feature\(["\']([^"\']+)["\']\)', code_section)
    if feature_match:
        feature = feature_match.group(1).strip()
        slug = re.sub(r'[^a-zA-Z0-9]+', '_', feature).strip('_').lower()
        return f"tests/ui/test_{slug}.py"

    class_match = re.search(r'class\s+(Test\w+)', code_section)
    if class_match:
        class_name = class_match.group(1)
        slug = re.sub(r'(?<!^)(?=[A-Z])', '_', class_name).lower()
        return f"tests/ui/{slug}.py"

    return f"tests/ui/test_ai_generated_{req_hash}.py"


def _save_script_to_file(script_content: str, req_hash: str) -> list:
    saved_paths = []
    target_rel = _derive_script_filename(script_content, req_hash)
    target_path = _PROJECT_ROOT / target_rel

    code = script_content
    fence_match = re.search(r'```(?:python)?\s*\n([\s\S]+?)```', script_content)
    if fence_match:
        code = fence_match.group(1)
    else:
        import_match = re.search(r'^(?:import |from )', script_content, re.MULTILINE)
        if import_match:
            code = script_content[import_match.start():]

    code = code.strip()
    if not code:
        print("  [AutomationAgent] ⚠️  No Python code found — skipping file save.")
        return saved_paths

    code = f"{_AI_GENERATED_MARKER}\n{code}"
    target_path.parent.mkdir(parents=True, exist_ok=True)

    if target_path.exists():
        existing = target_path.read_text(encoding="utf-8")
        if _AI_GENERATED_MARKER not in existing:
            stem = target_path.stem
            safe_rel = str(target_rel).replace(
                target_path.name, f"{stem}_ai_{req_hash[:8]}.py"
            )
            target_path = _PROJECT_ROOT / safe_rel
            target_rel = safe_rel
            print(f"  [AutomationAgent] ⚠️  Hand-written file detected — saving to: {target_rel}")
        else:
            print(f"  [AutomationAgent] ♻️  Overwriting previous AI script: {target_rel}")
    else:
        print(f"  [AutomationAgent] 📝 Writing new AI script: {target_rel}")

    target_path.write_text(code, encoding="utf-8")
    print(f"  [AutomationAgent] ✅ Script saved → {target_path}")
    saved_paths.append(str(target_path))
    return saved_paths


