    def _print_decision(self, decision) -> None:
        icon = "✅" if decision.proceed else "🛑"
        print(f"  {icon} Decision: {decision.reason}")
        for warning in decision.warnings:
            print(f"  ⚠️  {warning}")
        if decision.action_required:
            print(f"  📋 Action required: {decision.action_required}")

