"""
AI QA Orchestrator — Full Agile Pipeline Workflow
==================================================
Implements the complete 22-stage Agile QA lifecycle:

  Jira/User Story
      ↓ [1]  Requirement Understanding      (StoryAnalyzer)
      ↓ [2]  Acceptance Criteria Analysis   (StoryAnalyzer — section 3)
      ↓ [3]  Requirement Ambiguity Detection (AmbiguityAnalyzer) ← GATE
      ↓ [4]  Impact Analysis                (ImpactAnalyzer)
      ↓ [5]  Risk Analysis                  (DefectPredictionAgent)
      ↓ [6]  Test Strategy / Key Scenarios  (KeyScenarioAgent)
      ↓ [7]  Test Case Generation           (TestGenerator)
      ↓ [8]  Test Case Review               (ReviewAgent) ← GATE
      ↓ [9]  Automation Feasibility         (AutomationRecommendationAgent)
      ↓ [10] Framework Reuse Analysis       (FrameworkReuseAgent)
      ↓ [11] Automation Code Generation     (AutomationAgent)
      ↓ [12] Automation Code Review         (AutomationReviewAgent) ← GATE + RETRY
      ↓ [13] Test Data Generation           (DataAgent)
      ↓ [14] RTM Generation                 (RTMAgent)
      ↓ [15] RTM Compliance Validation      (DecisionEngine) ← GATE
      ↓ [16] Pytest Execution               (subprocess — optional)
      ↓ [17] Failure Analysis               (TestReportAnalyzerAgent — optional)
      ↓ [18] Defect Classification          (DefectClassifierAgent — optional)
      ↓ [19] RTM Update                     (PipelineStateManager)
      ↓ [20] AI Dashboard                   (AIDashboardAgent)
      ↓ [21] Sprint QA Summary              (SprintSummaryAgent)
      ↓ [22] Retrospective Insights         (RetrospectiveAgent)

Architectural Principles:
  AI DECIDES / RECOMMENDS — agents produce outputs
  CODE VALIDATES — DecisionEngine applies deterministic rules
  FRAMEWORK EXECUTES — pytest runs the actual tests
  HUMAN APPROVES CRITICAL DECISIONS — ambiguity gate, release decision
  RTM PROVIDES TRACEABILITY — every artifact linked to requirements

Usage:
    from ai_orchestrator.orchestrator.workflow import AgileQAWorkflow

    workflow = AgileQAWorkflow()
    context = workflow.run(
        requirement="User Story: ...",
        jira_story_id="HRM-202",
        force_rerun=False,
        run_tests=False,       # set True to execute pytest after generation
        pause_on_ambiguity=True,  # set False to proceed despite ambiguities
    )
    print(context.sprint_summary)
"""

